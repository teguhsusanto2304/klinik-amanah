    created_at TIMESTAMP NULL,
    updated_at TIMESTAMP NULL,
    UNIQUE KEY bills_visit_id_unique (visit_id),
    UNIQUE KEY bills_clinic_id_number_unique (clinic_id, number),
    KEY bills_clinic_id_status_index (clinic_id, status),
    KEY bills_guarantor_id_status_index (guarantor_id, status),
    CONSTRAINT bills_clinic_id_foreign FOREIGN KEY (clinic_id) REFERENCES clinics (id) ON DELETE CASCADE,
