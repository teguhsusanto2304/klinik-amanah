CREATE TABLE payments (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    clinic_id BIGINT UNSIGNED NOT NULL,
    bill_id BIGINT UNSIGNED NOT NULL,
    cash_session_id BIGINT UNSIGNED NULL,
    user_id BIGINT UNSIGNED NULL,
    number VARCHAR(30) NOT NULL,
    payer_type VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL,
    paid_at TIMESTAMP NOT NULL,
    amount DECIMAL(15,2) NOT NULL DEFAULT 0,
    tendered DECIMAL(15,2) NOT NULL DEFAULT 0,
    change_amount DECIMAL(15,2) NOT NULL DEFAULT 0,
    notes TEXT NULL,
    cancelled_at TIMESTAMP NULL,
    cancelled_by BIGINT UNSIGNED NULL,
    cancellation_reason VARCHAR(255) NULL,
    created_at TIMESTAMP NULL,
    updated_at TIMESTAMP NULL,
    UNIQUE KEY payments_clinic_id_number_unique (clinic_id, number),
    KEY payments_clinic_id_paid_at_index (clinic_id, paid_at),
    KEY payments_user_id_paid_at_index (user_id, paid_at),
    CONSTRAINT payments_clinic_id_foreign FOREIGN KEY (clinic_id) REFERENCES clinics (id) ON DELETE CASCADE,
    CONSTRAINT payments_bill_id_foreign FOREIGN KEY (bill_id) REFERENCES bills (id) ON DELETE CASCADE,
    CONSTRAINT payments_cash_session_id_foreign FOREIGN KEY (cash_session_id) REFERENCES cash_sessions (id) ON DELETE SET NULL,
    CONSTRAINT payments_user_id_foreign FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT payments_cancelled_by_foreign FOREIGN KEY (cancelled_by) REFERENCES users (id) ON DELETE SET NULL
