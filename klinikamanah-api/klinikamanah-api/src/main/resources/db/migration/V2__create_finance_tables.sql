-- Tabel modul keuangan (lihat dokumentasi bagian 9) beserta sumber biaya kunjungan yang ditagihkan otomatis:
-- tindakan medis, tindakan keperawatan, pemeriksaan laboratorium dan penjualan farmasi.
-- Tabel sumber biaya hanya memuat kolom yang dibaca modul keuangan; modul klinisnya dikelola aplikasi lain.

CREATE TABLE service_tariffs (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    clinic_id BIGINT UNSIGNED NOT NULL,
    code VARCHAR(20) NOT NULL,
    name VARCHAR(255) NOT NULL,
    category VARCHAR(30) NOT NULL,
    price DECIMAL(15,2) NOT NULL DEFAULT 0,
    description TEXT NULL,
    is_active TINYINT(1) NOT NULL DEFAULT 1,
    created_at TIMESTAMP NULL,
    updated_at TIMESTAMP NULL,
    UNIQUE KEY service_tariffs_clinic_id_code_unique (clinic_id, code),
    KEY service_tariffs_clinic_id_category_index (clinic_id, category),
    CONSTRAINT service_tariffs_clinic_id_foreign FOREIGN KEY (clinic_id) REFERENCES clinics (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE cash_sessions (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    clinic_id BIGINT UNSIGNED NOT NULL,
    user_id BIGINT UNSIGNED NULL,
    number VARCHAR(30) NOT NULL,
    status VARCHAR(20) NOT NULL,
    opened_at TIMESTAMP NOT NULL,
    opening_balance DECIMAL(15,2) NOT NULL DEFAULT 0,
    opening_notes TEXT NULL,
    closed_at TIMESTAMP NULL,
    expected_cash DECIMAL(15,2) NULL,
    counted_cash DECIMAL(15,2) NULL,
    difference DECIMAL(15,2) NULL,
    closing_notes TEXT NULL,
    created_at TIMESTAMP NULL,
    updated_at TIMESTAMP NULL,
    UNIQUE KEY cash_sessions_clinic_id_number_unique (clinic_id, number),
    KEY cash_sessions_user_id_status_index (user_id, status),
    KEY cash_sessions_clinic_id_opened_at_index (clinic_id, opened_at),
    CONSTRAINT cash_sessions_clinic_id_foreign FOREIGN KEY (clinic_id) REFERENCES clinics (id) ON DELETE CASCADE,
    CONSTRAINT cash_sessions_user_id_foreign FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

